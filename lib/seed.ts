import { Idea } from './types';
import { newId, now } from './storage';

// 初回起動時に入っているアイディアたち。
// 「こういうノリのものを入れる箱だよ」という見本を兼ねる。

function idea(
  title: string,
  body: string,
  tags: string[],
  excitement: 1 | 2 | 3
): Idea {
  const t = now();
  return {
    id: newId(),
    title,
    body,
    tags,
    excitement,
    stage: 'seed',
    createdAt: t,
    updatedAt: t,
  };
}

